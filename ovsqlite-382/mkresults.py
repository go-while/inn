P = 4096


def load(pattern):
    out = []
    for f in sorted(glob.glob(os.path.join(Z, pattern))):
        for n, ln in enumerate(open(f), 1):
            r = json.loads(ln)
            r['src'] = '%s:%d' % (os.path.relpath(f, Z), n)
            r['bad'] = bool(r.get('error'))
            out.append(r)
    return out


def frames(r):
    """WAL frames F (24-byte header + page), checkpoint pages K (one page) and WAL
    header writes H (32 bytes), solved exactly from the server's pwrite calls and
    bytes: calls = 2F + K + H, bytes = (24 + P)F + P*K + 32H.  4 KiB pages only."""
    n, w = r.get('dt_N_pwrite'), r.get('dt_W_pwrite')
    if r['page'] != P or n is None or w is None:
        return None
    for h in range(50):
        num = P * (n - h) - (w - 32 * h)
        if num >= 0 and num % (P - 24) == 0:
            f = num // (P - 24)
            k = n - h - 2 * f
            if k >= 0:
                return f, k, h
    return None


def ckpts(r):
    """Checkpoints in the window: each makes 2 fdatasync calls, and each WAL restart
    (header write) one more.  Needs the fixed DTrace window (round r3)."""
    fk = frames(r)
    if fk is None or 'dt_S_fdatasync' not in r:
        return None
    return (r['dt_S_fdatasync'] - fk[2]) // 2


def disk(r):
    return r['dev_kw'] / r['win_s']


def srv(r):
    return r['dt_W_pwrite'] / 1024 / r['accepted']


def walend(r):
    s = r.get('size-wal', 0)
    return (s - 32) // (P + 24) if s > 32 else 0


def rng(v, fmt='%.1f'):
    v = list(v)
    lo, hi = fmt % min(v), fmt % max(v)
    return lo if lo == hi else '%s–%s' % (lo, hi)


def pct(a, b):
    return abs(a - b) / min(a, b) * 100


