#!/usr/bin/env python3
# Make RESULTS.md from the raw results-*.jsonl in zfs/ (parse only; no measurement).
# usage: python3 -I mkresults.py > RESULTS.md
import collections
import glob
import json
import os
import statistics

Z = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'zfs')
CFG = [('up', 'Today'), ('ttl1', '`transtimelimit: 1`'), ('proto', 'Prototype')]
RS = ['16K', '32K', '64K', '128K']


def load(pattern):
    out = []
    for f in sorted(glob.glob(os.path.join(Z, pattern))):
        for n, ln in enumerate(open(f), 1):
            r = json.loads(ln)
            r['_src'] = '%s:%d' % (os.path.relpath(f, Z), n)
            if not r.get('error'):
                out.append(r)
    return out


def frames(r):
    """Split the server's pwrite calls into WAL frames F (header 24 B + page),
    checkpoint pages K (one page each) and WAL header writes H (32 B), exactly:
    calls = 2F + K + H, bytes = (24 + p)F + pK + 32H.  Only for 4 KiB pages."""
    p, n, w = r['page'], r.get('dt_N_pwrite'), r.get('dt_W_pwrite')
    if p != 4096 or n is None or w is None:
        return None
    for h in range(0, 50):
        num = p * (n - h) - (w - 32 * h)          # = (2p - (24 + p)) F = (p - 24) F
        if num >= 0 and num % (p - 24) == 0:
            f = num // (p - 24)
            k = n - h - 2 * f
            if k >= 0:
                return f, k, h
    return None


def rng(v, fmt='%.1f'):
    lo, hi = fmt % min(v), fmt % max(v)
    return lo if lo == hi else '%s–%s' % (lo, hi)


def disk(r):
    return r['dev_kw'] / r['win_s']


def srv(r):
    return r['dt_W_pwrite'] / 1024 / r['accepted']


r3 = [r for r in load('2026-11-15-r3/results-job*.jsonl') if r['win_s'] > 61]
r3_main = [r for r in r3 if r['page'] == 4096 and r['rate'] in (0.5, 2) and r['win_s'] > 500
           and 'dtfail' not in r['_src']]
r3_rep = [r for r in r3 if 'dtfail' in r['_src']]
r2 = load('2026-11-15-r2/results-job*.jsonl')
old = load('2026-11-14/results.jsonl')

print('''# ovsqlite write measurements for InterNetNews/inn#382: results

Generated by `mkresults.py` from the raw `zfs/*/results-*.jsonl` files; no number here is typed by hand.
Each `results-*.jsonl` line is one run; `_src` below means file:line.

## What was measured

- FreeBSD 15.1 in a VM (4 vCPUs, 3 GiB RAM), INN at main 4c5218607 with and without the prototype commit 47472af18.
- The overview is a ZFS dataset on a 5 GiB virtual disk of its own (compression on), recreated for each run and seeded with the same database: 300,000 articles in 200 groups, 57 MB.
- Articles are synthetic (one identical 40-line body, one group each, so one overview row per article) and go to the `trash` storage method, so only the overview writes.
- Articles are fed at a fixed, evenly spaced rate (no bursts); after a warm-up (20 s; 30 s for the 0.04/s runs) one window is measured.
- Configurations: **Today** = stock server (commits 10 s after a transaction starts); **`transtimelimit: 1`**; **Prototype** = also commits after 250 ms without a further write.

Columns:

- **server KiB/article**: bytes ovsqlite-server passed to `pwrite` (DTrace) per accepted article; this is SQLite's own output, and it matched the ZFS dataset's logical write counter (`nwritten`) within 0.4 % in every 4 KiB-page run of round r3.
- **WAL frames/article**: pages appended to the WAL per article, solved exactly from the pwrite calls and bytes (frame = 24-byte header + page; checkpoint page = one page; WAL header = 32 bytes).
- **checkpoint pages**: pages copied from the WAL into the database file in the window (a checkpoint runs once the WAL holds 1000 frames, `walcheckpointthreshold`).
- **disk KiB/s**: bytes written to the pool's virtual disk per second (`iostat -I`), as seen by the guest.
''')

print('## 1. 4 KiB pages, 600-second windows (round r3)\n')
print('One run per row; recordsize 16K, 32K, 64K and 128K each ran in their own jobs, at different times.\n')
print('| rate/s | config | recordsize | server KiB/article | WAL frames/article | checkpoint pages | disk KiB/s | accepted |')
print('|---|---|---|---|---|---|---|---|')
for rate in (0.5, 2):
    for c, name in CFG:
        for rs in RS:
            for r in [x for x in r3_main if x['rate'] == rate and x['cfg'] == c and x['rs'] == rs]:
                fk = frames(r)
                print('| %s | %s | %s | %.2f | %s | %s | %.1f | %d |' % (
                    rate, name, rs, srv(r), '%.2f' % (fk[0] / r['accepted']) if fk else '–',
                    fk[1] if fk else '–', disk(r), r['accepted']))
print()

print('Summary of section 1 (min–max over the four recordsizes, one run each):\n')
print('| rate/s | | ' + ' | '.join(n for _, n in CFG) + ' |')
print('|---|---|---|---|---|')
for rate in (0.5, 2):
    for label, fn, fmt in (('server KiB/article', srv, '%.1f'),
                           ('WAL frames/article', lambda r: frames(r)[0] / r['accepted'], '%.2f'),
                           ('checkpoint pages', lambda r: frames(r)[1], '%d'),
                           ('disk KiB/s', disk, '%.0f')):
        cells = []
        for c, _ in CFG:
            v = [fn(r) for r in r3_main if r['rate'] == rate and r['cfg'] == c]
            cells.append(rng(v, fmt))
        print('| %s | %s | %s |' % (rate, label, ' | '.join(cells)))
print()

print('## 2. Repeat runs of the same cell\n')
print('| cell | run A disk KiB/s | run B disk KiB/s | difference | source |')
print('|---|---|---|---|---|')
for a in r3_rep:
    b = [x for x in r3_main if x['rs'] == a['rs'] and x['rate'] == a['rate'] and x['cfg'] == a['cfg']]
    if b:
        b = b[0]
        print('| %s %s/s %s | %.1f | %.1f | %.1f %% | %s, %s |' % (
            a['rs'], a['rate'], a['cfg'], disk(a), disk(b), abs(disk(a) - disk(b)) / min(disk(a), disk(b)) * 100,
            a['_src'], b['_src']))
r2_600 = [r for r in r2 if r['rate'] == 0.5 and r['win_s'] > 500]
for a in r2_600:
    b = [x for x in r3_main if x['rs'] == '128K' and x['rate'] == 0.5 and x['cfg'] == a['cfg']]
    if b:
        b = b[0]
        print('| 128K 0.5/s %s | %.1f | %.1f | %.1f %% | %s, %s |' % (
            a['cfg'], disk(a), disk(b), abs(disk(a) - disk(b)) / min(disk(a), disk(b)) * 100, a['_src'], b['_src']))
print()

print('## 3. 10 articles/s, 90-second windows\n')
print('Disk only (the 2026-11-14 and r2 rounds counted the server bytes with an older DTrace window; their disk figures are not affected).\n')
print('| recordsize | config | runs | disk KiB/s | sources |')
print('|---|---|---|---|---|')
ten = [r for r in r3 + r2 + old if r['rate'] == 10 and r['page'] == 4096]
for rs in RS:
    for c, name in CFG:
        v = [r for r in ten if r['rs'] == rs and r['cfg'] == c]
        if v:
            print('| %s | %s | %d | %s | %s |' % (rs, name, len(v), rng([disk(r) for r in v]),
                                                  ', '.join(sorted({r['_src'].split(':')[0] for r in v}))))
print()

print('## 4. 0.04 articles/s, 30-minute windows (round r2, recordsize 128K, one run each)\n')
print('Older DTrace window: the frame counts can include one extra commit; disk figures are not affected.\n')
print('| config | accepted | disk KiB/s | server KiB/article | WAL frames/article | source |')
print('|---|---|---|---|---|---|')
for c, name in CFG:
    for r in [x for x in r2 if x['rate'] == 0.04 and x['cfg'] == c]:
        fk = frames(r)
        print('| %s | %d | %.2f | %.2f | %s | %s |' % (name, r['accepted'], disk(r), srv(r),
                                                     '%.2f' % (fk[0] / r['accepted']) if fk else '–', r['_src']))
print()

print('## 5. Idle (round r3, 128K, 90 seconds)\n')
print('| config | disk KiB | server pwrite bytes | source |')
print('|---|---|---|---|')
for r in [x for x in r3 if x['rate'] == 0]:
    print('| %s | %.0f | %d | %s |' % (dict(CFG)[r['cfg']], r['dev_kw'], r['dt_W_pwrite'], r['_src']))
print()

print('''## Caveats

- One run per cell in section 1; repeat runs of the same cell differed by the amounts in section 2, and each recordsize ran at a different time, so recordsize differences of that size cannot be told from noise.
- The windows end at a fixed time, not at a checkpoint: at 0.5/s, Today did not reach its 1000-frame checkpoint within 600 s while the other two did, which inflates their difference in that row. At 2/s every configuration checkpointed 2–4 times.
- Evenly spaced synthetic articles that compress well, one 57 MB database, one VM with a virtual disk; real traffic arrives in bursts and its overview data compresses less.
- With 16 KiB SQLite pages (round r3, jobs 10–11) the server's pwrite bytes exceed the dataset's `nwritten` by 4–40 MB per window, i.e. writes to files outside that dataset; they are not identified and not in the disk figures.
''')
